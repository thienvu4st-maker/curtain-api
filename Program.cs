using System.Text;
using media_app_api.Data;
using media_app_api.Services;
using Microsoft.AspNetCore.Authentication.JwtBearer;
using Microsoft.AspNetCore.Diagnostics;
using Microsoft.EntityFrameworkCore;
using Microsoft.IdentityModel.Tokens;

AppContext.SetSwitch("Npgsql.EnableLegacyTimestampBehavior", true);

var builder = WebApplication.CreateBuilder(args);

// --- 1. Database & Services ---
var connectionString = builder.Configuration.GetConnectionString("DefaultConnection");
builder.Services.AddDbContext<AppDbContext>(options =>
{
    if (connectionString != null && (connectionString.Contains("Host=") || connectionString.Contains("postgresql://")))
    {
        options.UseNpgsql(connectionString);
    }
    else
    {
        options.UseSqlServer(connectionString);
    }
});

builder.Services.AddScoped<IProductService, ProductService>();
builder.Services.AddScoped<ICategoryService, CategoryService>();
builder.Services.AddScoped<IAuthService, AuthService>();
builder.Services.AddScoped<IBookingService, BookingService>();

// --- 2. JWT Authentication ---
var jwtSecret = builder.Configuration["Jwt:Secret"]
    ?? throw new InvalidOperationException("Jwt:Secret is not configured in appsettings.json or environment variables.");
builder.Services.AddAuthentication(options =>
{
    options.DefaultAuthenticateScheme = JwtBearerDefaults.AuthenticationScheme;
    options.DefaultChallengeScheme = JwtBearerDefaults.AuthenticationScheme;
})
.AddJwtBearer(options =>
{
    options.TokenValidationParameters = new TokenValidationParameters
    {
        ValidateIssuer = true,
        ValidateAudience = true,
        ValidateLifetime = true,
        ValidateIssuerSigningKey = true,
        ValidIssuer = builder.Configuration["Jwt:Issuer"] ?? "MediaAppApi",
        ValidAudience = builder.Configuration["Jwt:Audience"] ?? "MediaAppClient",
        IssuerSigningKey = new SymmetricSecurityKey(Encoding.UTF8.GetBytes(jwtSecret)),
        ClockSkew = TimeSpan.Zero
    };
});

builder.Services.AddAuthorization();
builder.Services.AddControllers();

// --- 3. CORS Policy for Flutter Web & Mobile ---
builder.Services.AddCors(options =>
{
    options.AddPolicy("AllowFlutter", policy =>
    {
        policy.SetIsOriginAllowed(origin => true)
              .AllowAnyMethod()
              .AllowAnyHeader()
              .AllowCredentials();
    });
});

var app = builder.Build();

// --- 4. Global Exception Handler Middleware ---
app.UseExceptionHandler(errorApp =>
{
    errorApp.Run(async context =>
    {
        context.Response.StatusCode = 500;
        context.Response.ContentType = "application/json";

        var exceptionHandlerPathFeature = context.Features.Get<IExceptionHandlerPathFeature>();
        var ex = exceptionHandlerPathFeature?.Error;

        var result = System.Text.Json.JsonSerializer.Serialize(new
        {
            message = ex?.Message ?? "Internal Server Error",
            innerError = ex?.InnerException?.Message
        });

        await context.Response.WriteAsync(result);
    });
});

// --- 5. Database Schema Auto-Migration ---
using (var scope = app.Services.CreateScope())
{
    var dbContext = scope.ServiceProvider.GetRequiredService<AppDbContext>();
    dbContext.Database.EnsureCreated();

    var migrationSql = @"
        CREATE TABLE IF NOT EXISTS ""Categories"" (
            ""Id"" integer GENERATED BY DEFAULT AS IDENTITY,
            ""Name"" character varying(100) NOT NULL,
            ""Description"" character varying(500) NOT NULL DEFAULT '',
            ""IconName"" character varying(100) NOT NULL DEFAULT 'curtain',
            ""CreatedAt"" timestamp with time zone NOT NULL DEFAULT (now()),
            CONSTRAINT ""PK_Categories"" PRIMARY KEY (""Id"")
        );

        CREATE TABLE IF NOT EXISTS ""Bookings"" (
            ""Id"" integer GENERATED BY DEFAULT AS IDENTITY,
            ""CustomerName"" character varying(100) NOT NULL,
            ""PhoneNumber"" character varying(20) NOT NULL,
            ""Address"" character varying(300) NOT NULL DEFAULT '',
            ""ServiceType"" character varying(100) NOT NULL DEFAULT 'Thi công Rèm Cửa',
            ""Notes"" character varying(1000) NOT NULL DEFAULT '',
            ""Status"" character varying(50) NOT NULL DEFAULT 'Pending',
            ""CreatedAt"" timestamp with time zone NOT NULL DEFAULT (now()),
            CONSTRAINT ""PK_Bookings"" PRIMARY KEY (""Id"")
        );

        ALTER TABLE ""Products"" ADD COLUMN IF NOT EXISTS ""CategoryId"" integer;
        ALTER TABLE ""Products"" ADD COLUMN IF NOT EXISTS ""ImageUrl"" character varying(500) DEFAULT '';

        -- Drop NOT NULL constraint on legacy 'Category' column if present
        DO $$
        BEGIN
            IF EXISTS (
                SELECT 1 
                FROM information_schema.columns 
                WHERE table_name = 'Products' AND column_name = 'Category'
            ) THEN
                ALTER TABLE ""Products"" ALTER COLUMN ""Category"" DROP NOT NULL;
            END IF;
        END $$;

        -- Initialize Real Business Categories for Curtain & Interior Paneling & Washing Services
        INSERT INTO ""Categories"" (""Id"", ""Name"", ""Description"", ""IconName"", ""CreatedAt"")
        VALUES 
            (1, 'Màn Rèm Cửa', 'Rèm vải, rèm cuốn, rèm sáo gỗ, rèm cầu vồng cao cấp', 'curtains', NOW()),
            (2, 'Giấy Dán Tường', 'Giấy dán tường Hàn Quốc, Nhật Bản & Tranh 3D trang trí', 'wallpaper', NOW()),
            (3, 'Tấm Ốp Tường Nhựa (PVC & Lam Sóng)', 'Tấm ốp nhựa PVC giả đá, ốp tường Nano & Lam sóng cao cấp', 'wall_panel', NOW()),
            (4, 'Dịch Vụ Giặt Màn Rèm', 'Dịch vụ tháo lắp, vệ sinh & giặt hấp màn rèm tận nơi', 'cleaning', NOW())
        ON CONFLICT (""Id"") DO NOTHING;

        -- Seed sample booking request if empty
        INSERT INTO ""Bookings"" (""CustomerName"", ""PhoneNumber"", ""Address"", ""ServiceType"", ""Notes"", ""Status"", ""CreatedAt"")
        SELECT 'Anh Minh (Ví dụ)', '0987654321', '123 Nguyễn Trãi, Thanh Xuân, Hà Nội', 'Đo đạc thi công Rèm Cửa & Ốp Tường', 'Cần tư vấn mẫu ốp tường nhựa PVC giả đá phòng khách và rèm vải phòng ngủ', 'Pending', NOW()
        WHERE NOT EXISTS (SELECT 1 FROM ""Bookings"");

        -- Synchronize PostgreSQL IDENTITY Sequences
        SELECT setval(pg_get_serial_sequence('""Products""', 'Id'), coalesce(max(""Id""), 1)) FROM ""Products"";
        SELECT setval(pg_get_serial_sequence('""Categories""', 'Id'), coalesce(max(""Id""), 1)) FROM ""Categories"";
        SELECT setval(pg_get_serial_sequence('""Bookings""', 'Id'), coalesce(max(""Id""), 1)) FROM ""Bookings"";
    ";

    try
    {
        dbContext.Database.ExecuteSqlRaw(migrationSql);
    }
    catch (Exception ex)
    {
        Console.WriteLine($"Migration log: {ex.Message}");
    }
}

// --- 6. Clean Middleware Pipeline ---
app.UseRouting();
app.UseCors("AllowFlutter");
app.UseAuthentication();
app.UseAuthorization();
app.MapControllers();

app.Run();
